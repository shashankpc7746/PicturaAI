"""
Public site configuration, security headers and SEO files — PicturaAI
======================================================================
Everything here is derived from environment variables once at startup:

* ``/app/config.js``   — the browser's ``window.PICTURA_CONFIG`` (public values only)
* Content-Security-Policy — built from the same config, so optional third parties
  (Cloudflare Web Analytics, Sentry) are allowed only when they are configured
* ``/robots.txt`` and ``/sitemap.xml``
"""
from __future__ import annotations

import json
import os
from dataclasses import dataclass
from typing import Iterable, List, Optional
from urllib.parse import urlsplit
from xml.sax.saxutils import escape as xml_escape

DEFAULT_SITE_URL = "https://picturaai-k7q6.onrender.com"
JSDELIVR = "https://cdn.jsdelivr.net"
# The app's only jsDelivr dependency is MediaPipe Tasks Vision ("Style the
# subject"). The CSP allows just this pinned package path, not the whole CDN
# (which would let injected markup load any npm package or GitHub file).
# Keep MEDIAPIPE_VERSION equal to MP_VERSION in
# frontend/assets/js/engine/segment.js (backend/tests/test_site.py checks it).
MEDIAPIPE_VERSION = "0.10.35"
MEDIAPIPE_CDN = f"{JSDELIVR}/npm/@mediapipe/tasks-vision@{MEDIAPIPE_VERSION}/"  # trailing / = path prefix
SENTRY_CDN = "https://browser.sentry-cdn.com"
SENTRY_INGEST = ("https://*.ingest.sentry.io", "https://*.ingest.us.sentry.io")
CF_INSIGHTS_SCRIPT = "https://static.cloudflareinsights.com"
CF_INSIGHTS_CONNECT = "https://cloudflareinsights.com"

# Paths whose pages are generated by FastAPI (Swagger UI / ReDoc) and need
# inline script and CDN styles; they get a relaxed but still restrictive policy.
DOCS_PATHS = ("/docs", "/redoc")

STATIC_PAGES = ("privacy.html", "terms.html", "credits.html")


def env_bool(name: str, default: bool) -> bool:
    value = os.environ.get(name)
    if value is None or not value.strip():
        return default
    return value.strip().lower() in ("1", "true", "yes", "on")


def _clean_site_url(raw: str) -> str:
    url = (raw or "").strip().rstrip("/")
    parts = urlsplit(url)
    if parts.scheme not in ("http", "https") or not parts.netloc:
        return DEFAULT_SITE_URL
    return f"{parts.scheme}://{parts.netloc}{parts.path}".rstrip("/")


def _origin_of(url: str) -> Optional[str]:
    parts = urlsplit((url or "").strip())
    if parts.scheme != "https" or not parts.hostname:
        return None
    host = parts.hostname
    port = f":{parts.port}" if parts.port else ""
    return f"https://{host}{port}"


@dataclass(frozen=True)
class SiteConfig:
    site_url: str = DEFAULT_SITE_URL
    sentry_dsn_frontend: str = ""
    cf_web_analytics_token: str = ""
    describe_enabled: bool = True
    describe_generates: bool = False
    csp_report_only: bool = False

    @classmethod
    def from_env(cls, describe_generates: bool = False) -> "SiteConfig":
        describe_enabled = env_bool("DESCRIBE_ENABLED", True)
        return cls(
            site_url=_clean_site_url(os.environ.get("PUBLIC_SITE_URL", DEFAULT_SITE_URL)),
            sentry_dsn_frontend=os.environ.get("SENTRY_DSN_FRONTEND", "").strip(),
            cf_web_analytics_token=os.environ.get("CF_WEB_ANALYTICS_TOKEN", "").strip(),
            describe_enabled=describe_enabled,
            describe_generates=describe_enabled and describe_generates,
            csp_report_only=env_bool("CSP_REPORT_ONLY", False),
        )

    # ── /app/config.js ────────────────────────────────────────────────────────
    def public_config(self) -> dict:
        return {
            "siteUrl": self.site_url,
            "sentryDsn": self.sentry_dsn_frontend or None,
            "cfWebAnalyticsToken": self.cf_web_analytics_token or None,
            "describeEnabled": self.describe_enabled,
            "describeGenerates": self.describe_generates,
        }

    def config_js(self) -> str:
        # json.dumps escapes quotes/backslashes; additionally escape characters
        # that could end a <script> block or break a JS string literal.
        payload = json.dumps(self.public_config(), ensure_ascii=True, sort_keys=True)
        payload = payload.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
        return (
            "// Generated by the PicturaAI server from public environment settings.\n"
            f"window.PICTURA_CONFIG = Object.freeze({payload});\n"
        )

    # ── Content-Security-Policy ───────────────────────────────────────────────
    def app_csp(self) -> str:
        script = ["'self'", MEDIAPIPE_CDN, "'wasm-unsafe-eval'"]
        connect = ["'self'", MEDIAPIPE_CDN]
        if self.cf_web_analytics_token:
            script.append(CF_INSIGHTS_SCRIPT)
            connect.append(CF_INSIGHTS_CONNECT)
        if self.sentry_dsn_frontend:
            script.append(SENTRY_CDN)
            connect.extend(SENTRY_INGEST)
            dsn_origin = _origin_of(self.sentry_dsn_frontend)
            if dsn_origin and not dsn_origin.endswith((".ingest.sentry.io", ".ingest.us.sentry.io")):
                connect.append(dsn_origin)  # self-hosted Sentry
        return _join([
            ("default-src", ["'self'"]),
            ("script-src", script),
            ("style-src", ["'self'", "https://fonts.googleapis.com"]),
            ("font-src", ["'self'", "https://fonts.gstatic.com"]),
            ("img-src", ["'self'", "data:", "blob:"]),
            ("media-src", ["'self'", "blob:"]),
            ("connect-src", connect),
            ("worker-src", ["'self'", "blob:"]),
            ("manifest-src", ["'self'"]),
            ("object-src", ["'none'"]),
            ("base-uri", ["'self'"]),
            ("form-action", ["'self'"]),
            ("frame-ancestors", ["'none'"]),
        ])

    @staticmethod
    def docs_csp() -> str:
        # Swagger UI / ReDoc: assets from jsDelivr, an inline bootstrap script,
        # inline styles, Google Fonts (ReDoc), a blob: worker (ReDoc), and the
        # FastAPI favicon.
        return _join([
            ("default-src", ["'self'"]),
            ("script-src", ["'self'", JSDELIVR, "'unsafe-inline'"]),
            ("style-src", ["'self'", JSDELIVR, "https://fonts.googleapis.com", "'unsafe-inline'"]),
            ("font-src", ["'self'", "https://fonts.gstatic.com", "data:"]),
            ("img-src", ["'self'", "data:", "blob:", "https://fastapi.tiangolo.com", "https://cdn.redoc.ly", JSDELIVR]),
            ("connect-src", ["'self'"]),
            ("worker-src", ["'self'", "blob:"]),
            ("object-src", ["'none'"]),
            ("base-uri", ["'self'"]),
            ("frame-ancestors", ["'none'"]),
        ])

    def csp_header_name(self) -> str:
        return "Content-Security-Policy-Report-Only" if self.csp_report_only else "Content-Security-Policy"

    # ── SEO files ─────────────────────────────────────────────────────────────
    def robots_txt(self) -> str:
        return (
            "User-agent: *\n"
            "Allow: /\n"
            "Disallow: /api/\n"
            "Disallow: /docs\n"
            "Disallow: /redoc\n"
            "\n"
            f"Sitemap: {self.site_url}/sitemap.xml\n"
        )

    def sitemap_urls(self, style_slugs: Iterable[str], include_styles_index: bool) -> List[str]:
        base = f"{self.site_url}/app"
        urls = [f"{base}/"]
        if include_styles_index:
            urls.append(f"{base}/styles/")
        urls.extend(f"{base}/styles/{slug}/" for slug in style_slugs)
        urls.extend(f"{base}/{page}" for page in STATIC_PAGES)
        return urls

    def sitemap_xml(self, style_slugs: Iterable[str], include_styles_index: bool) -> str:
        lines = [
            '<?xml version="1.0" encoding="UTF-8"?>',
            '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">',
        ]
        for url in self.sitemap_urls(style_slugs, include_styles_index):
            lines.append(f"  <url><loc>{xml_escape(url)}</loc></url>")
        lines.append("</urlset>")
        return "\n".join(lines) + "\n"


def _join(directives: list[tuple[str, list[str]]]) -> str:
    return "; ".join(f"{name} {' '.join(values)}" for name, values in directives)


def is_docs_path(path: str) -> bool:
    return any(path == p or path.startswith(p + "/") for p in DOCS_PATHS)


def is_https(scheme: str, forwarded_proto: Optional[str]) -> bool:
    if scheme == "https":
        return True
    first = (forwarded_proto or "").split(",")[0].strip().lower()
    return first == "https"
